#!/usr/bin/env python3
"""
Pull the constant tables the WebP decoder needs out of the specifications
and write them as a C header (user/libs/image/webp_tables.h).

  RFC 6386  VP8 Data Format and Decoding Guide   (lossy WebP)
  RFC 9649  WebP Image Format                    (lossless WebP's distance map)

The tables are long lists of numbers that have to be exactly right, so they
are copied by program rather than by hand. Each one's length is checked.

Usage: scripts/extract_webp_tables.py rfc6386.txt rfc9649.txt output.h
Get the RFCs from https://www.rfc-editor.org/rfc/rfc6386.txt and rfc9649.txt.
"""

import re
import sys


def clean(text):
    """Drop the page breaks (footer, form feed, header) the RFC text is cut into."""
    lines = []
    for line in text.split("\n"):
        if re.match(r"^(Bankoski, et al\.|RFC 6386|RFC 9649|Zern, et al\.)", line.strip()):
            continue
        lines.append(line.replace("\f", ""))
    return "\n".join(lines)


def numbers_after(text, marker, count, start_at=0):
    """The first `count` integers in the brace block that follows `marker`."""
    pos = text.find(marker, start_at)
    if pos < 0:
        sys.exit(f"not found: {marker}")
    brace = text.find("{", pos)
    depth, end = 0, brace
    while True:
        c = text[end]
        depth += c == "{"
        depth -= c == "}"
        end += 1
        if depth == 0:
            break
    block = text[brace:end]
    block = re.sub(r"/\*.*?\*/", " ", block, flags=re.S)   # comments
    block = re.sub(r"//[^\n]*", " ", block)
    values = [int(v) for v in re.findall(r"-?\d+", block)]
    if len(values) != count:
        sys.exit(f"{marker}: expected {count} numbers, found {len(values)}")
    return values


def c_array(name, ctype, values, per_line=16):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return f"static const {ctype} {name}[{len(values)}] = {{\n" + "\n".join(lines) + "\n};\n"


def main(argv):
    vp8 = clean(open(argv[1], encoding="utf-8").read())
    webp = clean(open(argv[2], encoding="utf-8").read())

    # kf_bmode_prob appears twice: a declaration first, the values "at the end of this section".
    first = vp8.find("const Prob kf_bmode_prob [num_intra_bmodes] [num_intra_bmodes]")
    tables = [
        ("kf_bmode_prob", "uint8_t",
         numbers_after(vp8, "const Prob kf_bmode_prob [num_intra_bmodes] [num_intra_bmodes]", 900, first + 10)),
        ("coeff_update_probs", "uint8_t", numbers_after(vp8, "const Prob coeff_update_probs [4] [8] [3]", 1056)),
        ("default_coeff_probs", "uint8_t", numbers_after(vp8, "const Prob default_coeff_probs [4] [8] [3]", 1056)),
        ("dc_qlookup", "int16_t", numbers_after(vp8, "static const int dc_qlookup[QINDEX_RANGE]", 128)),
        ("ac_qlookup", "int16_t", numbers_after(vp8, "static const int ac_qlookup[QINDEX_RANGE]", 128)),
    ]

    # The lossless distance map is a list of (x, y) pairs in the text, not a C array.
    start = webp.find("(0, 1),  (1, 0),")
    pairs = re.findall(r"\((-?\d+),\s*(-?\d+)\)", webp[start:start + 6000])[:120]
    if len(pairs) != 120:
        sys.exit(f"distance map: expected 120 pairs, found {len(pairs)}")
    distance_map = [int(v) for p in pairs for v in p]

    with open(argv[3], "w", newline="\n") as out:
        out.write("/* Generated by scripts/extract_webp_tables.py from RFC 6386 and RFC 9649. Don't edit. */\n\n")
        out.write("#pragma once\n\n#include <stdint.h>\n\n")
        out.write("/* VP8 (lossy WebP), RFC 6386. Flattened: [10][10][9], [4][8][3][11], [128]. */\n")
        for name, ctype, values in tables:
            out.write(c_array(name, ctype, values) + "\n")
        out.write("/* VP8L (lossless WebP), RFC 9649: the 120 (x, y) offsets of the distance map. */\n")
        out.write(c_array("vp8l_distance_map", "int8_t", distance_map) + "\n")
    print(f"wrote {argv[3]}")


if __name__ == "__main__":
    main(sys.argv)
